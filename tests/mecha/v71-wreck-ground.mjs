import assert from 'node:assert/strict';
import {wreckTerrainPoseV71,shardTerrainStepV71} from '../../examples/threejs/mech-wreck-ground-v71.js';
const basic={duration:2.25,baseY:0,scale:1,x:0,z:0,groundAt:()=>0};
const a=wreckTerrainPoseV71({...basic,elapsed:2.25});
assert.ok(a.y>=0&&a.clearance>=.017);
const h=wreckTerrainPoseV71({...basic,elapsed:2.25,heavy:true});
assert.ok(h.y>=0&&h.clearance>=.017);
const sloped=wreckTerrainPoseV71({...basic,elapsed:2.25,groundAt:x=>x<0?.15:0});
assert.ok(sloped.y>=a.y+.13);
const unknown=wreckTerrainPoseV71({...basic,elapsed:2.25,groundAt:()=>NaN});
assert.equal(unknown.groundVerified,false);
const bridge=wreckTerrainPoseV71({...basic,elapsed:2.25,groundAt:()=>15});
assert.equal(bridge.groundVerified,false);
const s={obj:{position:{x:0,y:.15,z:0}},floor:0,vx:2,vy:-2,vz:0};
const r=shardTerrainStepV71(s,.05,{groundAt:()=>.20});
assert.equal(r.verified,true);assert.ok(s.obj.position.y>=.222);
const fallback=shardTerrainStepV71(s,.05,{groundAt:()=>NaN});
assert.equal(fallback.verified,false);assert.ok(s.obj.position.y>=s.floor+.022);
console.log('PASS v7.1 genuine portable terrain math: skinned proxy support, sloped OSM, invalid bridge, shard ground and fallback');
