import assert from 'node:assert/strict';
import {terrainContact,createFootfallGate,createLaunchSettle} from '../../examples/threejs/mech-contact-v53.js';
assert.equal(terrainContact(null),null);
assert.equal(terrainContact({height:12,normal:{x:0,y:1,z:0}},0),null);
assert.equal(terrainContact({height:0,normal:{x:1,y:.1,z:0}}),null);
const slope=terrainContact({height:.12,normal:{x:.5,y:.866,z:0}},0);
assert.ok(slope && Math.abs(slope.tiltRadians-.24)<1e-8);
assert.equal(terrainContact({height:.03,normal:{x:0,y:1,z:0}}).tiltRadians,0);
const gate=createFootfallGate();
const p={side:'L',dt:.05,speed:3,error:.10,position:[0,0,0]};
assert.equal(gate.update({...p,stance:true}),null,'first planted frame is suppressed');
gate.update({...p,stance:false});
const event=gate.update({...p,stance:true});
assert.equal(event,null,'debounce interval');
gate.update({...p,stance:false,dt:.24});
const next=gate.update({...p,stance:true,dt:.24});
assert.ok(next && next.strength>0 && next.strength<.85,'moving stance yields actual step');
gate.update({...p,stance:false});
assert.equal(gate.update({...p,stance:true,speed:0,dt:.24}),null,'idle cannot step');
assert.equal(gate.update({...p,stance:false,error:3}),null);
const load=createLaunchSettle();assert.equal(load.update(.016,0).launch,0);
assert.ok(load.update(.016,2).launch>.7);
assert.ok(load.update(.016,0).settle>.7);
load.reset();assert.equal(load.update(.016,0).settle,0);
console.log('PASS v5.3: slope-normal rejection & capped tilt, footfall transition gate, inertia envelopes');
