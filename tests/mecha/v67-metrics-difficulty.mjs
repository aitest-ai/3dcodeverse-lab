import assert from 'node:assert/strict';
import {createBattleMetricsV67} from '../../examples/threejs/mech-battle-metrics-v67.js';
import {applyIncomingDamageV67,nextDifficultyV67} from '../../examples/threejs/mech-difficulty-v67.js';
assert.equal(applyIncomingDamageV67(16,'standard','player'),16);
assert.equal(applyIncomingDamageV67(16,'training','player'),12);
assert.equal(applyIncomingDamageV67(16,'challenge','player'),20);
assert.equal(applyIncomingDamageV67(16,'training','relay'),12);
assert.equal(applyIncomingDamageV67(16,'challenge','relay'),20);
assert.equal(nextDifficultyV67('challenge'),'training');
const m=createBattleMetricsV67();
m.begin({level:'training'});
m.record('wave_start',{wave:1,position:{x:11111,z:22222}});
for(let i=0;i<60;i++)m.observe(1/60,{mission:{phase:'combat',wave:1,active:true}});
m.record('player_shot',{weapon:'light',coordinates:{lat:21}});
m.record('enemy_hit',{damage:40,point:{x:999999}});
m.record('enemy_shot',{hit:true});
m.record('player_hit',{damage:12});
m.record('relay_hit',{damage:16});
m.record('dodge_started',{underWarning:true});
m.record('dodge_blocked');
m.record('route_replan');
assert.equal(m.report().difficulty,'training');
assert.equal(m.report().counts.playerShots,1);
assert.equal(m.report().counts.enemyHits,1);
assert.equal(m.report().counts.enemyShotsHit,1);
assert.equal(m.report().counts.dodgeAttempts,1);
assert.equal(m.report().counts.dodgeDuringWarnings,1);
assert.equal(m.report().counts.playerDamage,12);
assert.equal(m.report().waves.length,1);
assert.equal(m.report().waves[0].combatSeconds,1);
const json=JSON.stringify(m.report());
for(const s of ['11111','22222','999999','lat','userId','GPS'])assert.ok(!json.includes(s),'private value leaked '+s);
m.observe(.016,{mission:{phase:'victory',wave:1,finished:true}});
assert.equal(m.report().status,'complete');
assert.equal(m.record('enemy_hit',{damage:10}),false);
m.begin({level:'standard'});
assert.equal(m.report().counts.enemyHits,0);
console.log('PASS v6.7: difficulty exact, per-wave live aggregates, no raw coordinates, full reset');
