import assert from 'node:assert/strict';
import {createPortableFeedbackV64,FEEDBACK_TYPES_V64} from '../../examples/threejs/mech-feedback-kernel-v64.js';
const names=Object.keys(FEEDBACK_TYPES_V64);
for(const required of ['enemy_hit','enemy_down','relay_hit','heavy_arrival','victory','defeat','reset'])
 assert.ok(names.includes(required));
const f=createPortableFeedbackV64({historyLimit:3});
assert.equal(f.record('untrusted').accepted,false);
let cue=f.record('enemy_hit',{damage:40,distance:30,x:9999,z:1234});
assert.equal(cue.accepted,true);assert.equal(cue.label,'命中敵機 −40');
assert.ok(cue.intensity>0 && cue.intensity<FEEDBACK_TYPES_V64.enemy_hit.shake);
assert.equal(f.record('enemy_hit',{damage:40}).accepted,false);
for(let i=0;i<10;i++)f.update(.016);
assert.equal(f.record('relay_hit',{damage:16}).accepted,true);
assert.equal(f.record('building_hit').accepted,false);
assert.equal(f.snapshot().pending.label,'中繼站 −16');
for(let i=0;i<30;i++)f.update(.05);
assert.equal(f.snapshot().pending,null);
assert.equal(f.record('heavy_arrival',{wave:3}).cue,'boss');
assert.equal(f.record('victory').accepted,true);
assert.equal(f.record('enemy_hit',{damage:40}).accepted,false);
for(let i=0;i<155;i++)f.update(.05);
assert.equal(f.snapshot().pending,null);
f.record('enemy_hit',{damage:12});
assert.ok(f.snapshot().recent.length<=3);
assert.ok(!JSON.stringify(f.snapshot()).includes('9999'));
assert.equal(f.record('reset').accepted,true);
assert.equal(f.snapshot().recent.length,0);
f.dispose();assert.equal(f.record('victory').accepted,false);
console.log('PASS v6.4 portable feedback: real event labels, priority, rate limiting, effect bounds, no coordinates and reset');
