import assert from 'node:assert/strict';
import {createMissionDirectorV65,compassSectorV65} from '../../examples/threejs/mech-mission-director-v65.js';
import {createEnemyBrainV59} from '../../examples/threejs/mech-enemy-ai-v59.js';
const d=createMissionDirectorV65();
assert.deepEqual(d.wavePlan(1,['assault','assault']).map(x=>x.sector),['東側','西側']);
assert.deepEqual(d.wavePlan(2,['assault','ranger','assault']).map(x=>x.sector),['北側','南側','東側']);
assert.deepEqual(d.wavePlan(3,['assault','ranger','heavy','assault']).map(x=>x.sector),['西側','東側','北側','南側']);
assert.equal(compassSectorV65({x:22,z:0},{x:0,z:0}),'東側');
assert.equal(compassSectorV65({x:NaN,z:0},{x:0,z:0}),'未知');
d.start();assert.equal(d.snapshot().notice.kind,'opening');
d.observe({mission:{wave:1,phase:'combat',relayHP:100,relayMaxHP:100}});
assert.equal(d.snapshot().currentWave,1);assert.equal(d.snapshot().notice.kind,'opening');
d.confirmedSpawn(1,{x:33,z:0},{x:0,z:0},'assault');
assert.ok(!JSON.stringify(d.snapshot()).includes('"x":33'));
for(let i=0;i<60;i++)d.update(.05);
d.observe({mission:{wave:2,phase:'combat',relayHP:100,relayMaxHP:100}});
d.observe({mission:{wave:3,phase:'combat',relayHP:100,relayMaxHP:100},heavy:{hp:180,maxHp:180}});
const baseline=d.snapshot().totalEvents;
d.observe({mission:{wave:3,phase:'combat',relayHP:100,relayMaxHP:100},heavy:{hp:90,maxHp:180}});
assert.equal(d.snapshot().overdrive,true);
assert.ok(d.bossTuning('heavy').cooldownScale<1);
assert.equal(d.bossTuning('ranger').damageScale,1);
assert.equal(d.snapshot().totalEvents,baseline+1);
d.observe({mission:{wave:3,phase:'combat',relayHP:25,relayMaxHP:100},heavy:{hp:80,maxHp:180}});
assert.equal(d.snapshot().critical,true);
d.observe({mission:{wave:3,phase:'victory',relayHP:25,relayMaxHP:100}});
assert.equal(d.snapshot().finished,'victory');
assert.equal(d.bossTuning('heavy').overdrive,false);
const make=stage=>createEnemyBrainV59({role:'heavy',id:2}).update({dt:.016,position:{x:0,y:0,z:0},target:{x:90,y:0,z:0},stage,visible:false,canOccupy:()=>true,sampleGround:()=>0});
const original=make('normal'),fast=make('overdrive');
assert.ok(fast.speed>original.speed);
assert.ok(fast.position.x>original.position.x);
assert.ok(fast.windupTotal<original.windupTotal);
d.reset();assert.equal(d.snapshot().active,false);
console.log('PASS v6.5 portable: OSM candidate lane labels, HP gate, once-only stage, critical alert, no coordinates and heavy-only AI tune');
