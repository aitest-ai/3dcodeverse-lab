import assert from 'node:assert/strict';
import {createSmokeCityLimiterV75,SMOKE_CITY_SETTINGS_V75} from '../../examples/threejs/mech-smoke-city-v75.js';
const p=(x,y=1,z=0)=>({x,y,z});
const city=createSmokeCityLimiterV75();
const sweep=(x,z,y,r,fromX)=>fromX<1&&x>=1;
assert.equal(city.place(p(0),p(2),{wallAt:sweep}).reason,'wall');
const a=city.place(p(0),p(.5),{wallAt:sweep,groundAt:()=>0,requireGround:true});
assert.equal(a.accepted,true);assert.equal(a.floorSample,0);
assert.equal(city.place(p(0),p(.5),{wallAt:()=>false,groundAt:()=>50,requireGround:true,groundReference:0}).accepted,false);
assert.equal(city.place(p(0),p(.5),{wallAt:()=>false,groundAt:()=>NaN,requireGround:true}).accepted,false);
assert.equal(city.place(p(0),p(.5),{wallAt:()=>{throw Error('offline')}}).accepted,false);
for(let i=0;i<40;i++)city.place(p(0),p(.1),{wallAt:()=>false,groundAt:()=>0,requireGround:true});
assert.ok(city.stats().peakWalls<=16);assert.ok(city.stats().peakGround<=12);
assert.ok(city.stats().budgetHeld>0);
city.newFrame();city.setQuality('balanced');
for(let i=0;i<40;i++)city.place(p(0),p(.1),{wallAt:()=>false});
assert.ok(city.stats().wallQueries<=SMOKE_CITY_SETTINGS_V75.balanced.wallBudget);
city.newFrame();city.setQuality('light');
for(let i=0;i<40;i++)city.place(p(0),p(.1),{wallAt:()=>false});
assert.ok(city.stats().wallQueries<=6);
city.reset();assert.equal(city.stats().wallRejected,0);
console.log('PASS v7.5 shared source: full thin-wall sweep, separate-deck refusal, fail-closed callback and quality budgets');
