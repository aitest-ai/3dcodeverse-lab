import assert from 'node:assert/strict';
import {createTaipeiDefenseMissionV60,DEFENSE_WAVES_V60} from '../../examples/threejs/mech-mission-v60.js';
const site={x:3,y:0,z:5};
const m=createTaipeiDefenseMissionV60({betweenWaves:.2});
assert.equal(m.start({x:NaN,y:0,z:0}).ok,false);
assert.ok(m.start(site).ok);
assert.equal(m.deploy([1]),false,'partial unsafe wave may not pass');
assert.equal(m.snapshot().phase,'deployment_failed');
m.start(site);
assert.ok(m.deploy([1,2]));
m.destroyEnemy(1);assert.equal(m.destroyEnemy(1),false);
m.destroyEnemy(2);
assert.equal(m.snapshot().phase,'intermission');
const before=m.snapshot().remainingSeconds;m.tick(.05,{active:false});
assert.equal(m.snapshot().remainingSeconds,before);
for(let i=0;i<5;i++)m.tick(.05);
assert.equal(m.requestedWave().wave,2);
assert.ok(m.deploy([3,4,5]));
for(const id of [3,4,5])m.destroyEnemy(id);
for(let i=0;i<5;i++)m.tick(.05);
assert.equal(m.requestedWave().wave,3);
assert.deepEqual(m.requestedWave().roles,[...DEFENSE_WAVES_V60[2].roles]);
assert.ok(m.deploy([6,7,8,9]));
for(const id of [6,7,8,9])m.destroyEnemy(id);
assert.equal(m.snapshot().phase,'victory');assert.equal(m.snapshot().kills,9);
assert.equal(m.damageRelay(50),false);
m.start(site);m.deploy([1,2]);m.damageRelay(101);
assert.equal(m.snapshot().reason,'relay-destroyed');
m.start(site);m.deploy([1,2]);m.tick(.05,{playerHP:0});
assert.equal(m.snapshot().reason,'player-destroyed');
m.start(site);m.deploy([1,2]);m.tick(.05,{withinArea:false});
assert.equal(m.snapshot().reason,'left-defense-area');
m.start(site);m.deploy([1,2]);m.tick(500);
assert.ok(m.snapshot().remainingSeconds>299,'single stalled update cannot skip mission');
const timer=createTaipeiDefenseMissionV60({duration:30});timer.start(site);timer.deploy([1,2]);
for(let i=0;i<601;i++)timer.tick(.05);
assert.equal(timer.snapshot().reason,'time-expired');
console.log('PASS v6.0: 3 waves, safe deployment, hit-driven kills, relay/player defeat, timeout, pause and no instant frame jumps');
