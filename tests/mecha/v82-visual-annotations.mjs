import assert from 'node:assert/strict';
import {expectedFileNameV82,validateEvidenceV82,createVisualAnnotationV82,annotatedPixelV82,makeVisualReviewV82} from '../../examples/threejs/mech-frame-annotations-v82.js';
const expected=expectedFileNameV82(1,'beam_input');
assert.equal(expected,'Taipei_Mech_v81_input_01_beam_input.png');
const file={bytes:3100,width:960,height:540};
const evidence={schema:'taipei-mecha-v81-input-frame-evidence',version:'8.1',shots:[{index:1,action:'beam_input',elapsedMs:1000,framesAfterInput:3,bytes:3100}]};
const media=new Map([[expected,file]]);
const result=validateEvidenceV82(evidence,media);
assert.equal(result.ok,true);assert.equal(result.shots.length,1);
assert.equal(validateEvidenceV82(evidence,new Map()).ok,false);
assert.equal(validateEvidenceV82({...evidence,schema:'not-a-real-event'},media).ok,false);
assert.equal(validateEvidenceV82({...evidence,shots:[evidence.shots[0],evidence.shots[0]]},media).ok,false);
assert.throws(()=>expectedFileNameV82(0,'beam_input'));
const a=createVisualAnnotationV82({shotIndex:1,action:'beam_input',kind:'muzzle',x:0.45,y:0.25,detail:'manual visual marker'});
assert.deepEqual(annotatedPixelV82(a,960,540),{x:432,y:135});
assert.throws(()=>createVisualAnnotationV82({...a,x:1.01}));
assert.throws(()=>createVisualAnnotationV82({...a,severity:'untrusted'}));
assert.throws(()=>createVisualAnnotationV82({...a,detail:'x'.repeat(221)}));
assert.throws(()=>makeVisualReviewV82(result.shots,[{...a,shotIndex:2}]));
const report=makeVisualReviewV82(result.shots,[a],{manualReviewed:true});
assert.equal(report.schema,'taipei-mecha-v82-visual-annotations');
assert.equal(report.annotations[0].x,0.45);
assert.ok(!JSON.stringify(report).includes('worldCamera'));
assert.ok(!JSON.stringify(report).includes('data:image/png'));
assert.ok(report.limitations.includes('2D'));
console.log('PASS v8.2 annotation contract: evidence validation, strictly 2D normalized points, privacy, duplicate refusal');
